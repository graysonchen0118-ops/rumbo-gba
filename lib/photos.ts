export function idFoto(k: string): string {
  let clave = k;
  for (let i = 0; i < 4 && !IDS[clave]; i++) clave = CERCANO[clave] ?? "obelisco";
  return IDS[clave] ?? IDS.obelisco;
}

export function foto(k: string, w: number, h: number, cara = false) {
  const id = idFoto(k);
  return `https://images.unsplash.com/photo-${id}?w=${w}&h=${h}&fit=crop${cara ? "&crop=faces" : ""}&q=72&auto=format`;
}
